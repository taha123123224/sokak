"""server/supabase/v2_guvenlik_sablon.sql + catalog.json -> server/supabase/v2_guvenlik.sql"""
import json, os
d = os.path.join(os.path.dirname(__file__), '..', 'server', 'supabase')
cat = json.dumps(json.load(open(os.path.join(d, 'catalog.json'))), ensure_ascii=False, separators=(',', ':'))
s = open(os.path.join(d, 'v2_guvenlik_sablon.sql')).read().replace('__CATALOG__', cat)
open(os.path.join(d, 'v2_guvenlik.sql'), 'w').write(s)
print('ok', len(s))

# relay: per-weapon damage limits for hit validation
cj = json.load(open(os.path.join(d, 'catalog.json')))
lim = {k: {"dmg": v["dmg"], "head": v["head"], "pel": v["pellets"], "rpm": v["rpm"]} for k, v in cj["weapons"].items()}
rp = os.path.join(d, '..', 'relay', 'src', 'weapons.js')
open(rp, 'w').write('// generated by tools/build_sql.py from the game catalog — do not edit\nexport const WEAPONS = ' + json.dumps(lim, ensure_ascii=False) + ';\n')
print('relay weapons', len(lim))
